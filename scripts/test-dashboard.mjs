import assert from 'node:assert/strict';
import {build} from 'esbuild';
const out = new URL('../node_modules/.cache-dashboard-test.mjs', import.meta.url).pathname;
await build({stdin: {contents: "export * from './src/dashboard/themes'; export * from './src/dashboard/stats'; export * from './src/dashboard/music';", resolveDir: new URL('..', import.meta.url).pathname}, bundle: true, format: 'esm', platform: 'node', outfile: out, define: {'import.meta.glob': 'emptyCatalog'}, banner: {js: 'const emptyCatalog = () => ({});'}, logLevel: 'error'});
const d = await import(out);
const template = {version: 1, id: 'my-blades', name: 'My blades', layout: 'blades', accent: '#abcdef', palette: {bg: '#123456'}};
assert.equal(d.parseTheme(template).layout, 'blades');
for (const bad of [{...template, id: 'blades'}, {...template, id: '$(touch hacked)'}, {...template, accent: 'url(https://example.com)'}, {...template, palette: {overlay: 'url(evil)'}}, {...template, palette: {'__proto__': null, arbitrary: '#123456'}}, {...template, bladeColors: ['#000000']}]) assert.throws(() => d.parseTheme(bad));
assert.equal(d.parseTheme({...template,id:'custom-hearth',layout:'hearth'}).layout,'hearth');
assert.equal(d.BUILTIN_THEMES.find(t=>t.id==='hearth-plus').layout,'hearth');
const storage = new Map();
globalThis.localStorage = {getItem: (k) => storage.get(k) || null, setItem: (k, v) => storage.set(k, v)};
assert.equal(d.loadThemes('grey').active, 'grey');
d.saveThemes({active:'hearth-plus',installed:[]});
assert.equal(d.loadThemes().active,'hearth-plus');
assert.equal(d.activeTheme(d.loadThemes()).background,'wallpaper');
const theme = d.parseTheme(template);
d.saveThemes({active: theme.id, installed: [theme]});
assert.equal(d.activeTheme(d.loadThemes()).id, theme.id);
storage.set(d.THEME_KEY, JSON.stringify({active: 'missing', installed: [theme, {...theme, id: 'broken$'}, theme]}));
assert.equal(d.loadThemes().installed.length, 1);
assert.equal(d.loadThemes().active, 'black');
const text = '[cpu]\ncpu 100 0 40 300 10 0 0 0 20 0\n[memory]\nMemTotal: 1000 kB\nMemAvailable: 250 kB\n[uptime]\n90061 5000\n[load]\n1.00 2.00 3.00 2/20 4\n[temperature]\n55000\n[webos]\nPRETTY_NAME="webOS TV 5.6.2"\n';
const snapshot = d.parseSnapshot(text);
assert.equal(snapshot.memoryAvailable, 256000);
assert.equal(snapshot.temperature, '55 °C');
assert.equal(d.formatUptime(snapshot.uptime), '1d 1h 1m');
assert.equal(d.cpuUsage(null, snapshot), null);
assert.equal(d.cpuUsage(snapshot, {...snapshot, cpu: [140,0,60,340,10,0,0,0,30,0]}), 60, 'guest CPU time is not counted twice');
assert.equal(d.cpuUsage(snapshot, snapshot), null);
assert.throws(() => d.trackUrl({baseUrl: 'http://localhost:8766', token: 'abc'}, '../../secret'));
assert.equal(d.mediaTime(NaN), '0:00');
assert.equal(d.mediaTime(125), '2:05');
console.log('ok   theme validation, persistence, corrupt-file recovery, real stats parsing, CPU sampling and safe track URLs');
