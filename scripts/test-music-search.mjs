import assert from 'node:assert/strict';
import {build} from 'esbuild';
const out = new URL('../node_modules/.cache-music-search-test.mjs', import.meta.url).pathname;
await build({entryPoints: [new URL('../src/dashboard/search.ts', import.meta.url).pathname], bundle: true, format: 'esm', outfile: out, platform: 'node', logLevel: 'error'});
const s = await import(out);
const store = new Map();
globalThis.localStorage = {getItem: (k) => store.get(k) || null, setItem: (k, v) => store.set(k, v), removeItem: (k) => store.delete(k)};
s.rememberSearch('  First   search '); s.rememberSearch('second'); s.rememberSearch('FIRST search');
assert.deepEqual(s.readSearchHistory(), ['FIRST search', 'second']);
s.rememberSearch('constructor'); assert.equal(s.readSearchHistory()[0], 'constructor');
for (let i = 0; i < 25; i++) s.rememberSearch('query ' + i);
assert.equal(s.readSearchHistory().length, 20);
store.set(s.SEARCH_HISTORY_KEY, '{invalid'); assert.deepEqual(s.readSearchHistory(), []);
s.clearSearchHistory(); assert.equal(store.has(s.SEARCH_HISTORY_KEY), false);
const calls = [], states = [], deferred = [];
const wait = ms => new Promise(r => setTimeout(r, ms));
const engine = s.createLiveSearch(q => { calls.push(q); return new Promise((resolve, reject) => deferred.push({resolve, reject})); }, state => states.push(state), 5);
engine.setQuery('a'); engine.setQuery('ab'); await wait(15);
assert.deepEqual(calls, ['ab'], 'fast typing is debounced');
engine.setQuery('abc'); await wait(15);
assert.deepEqual(calls, ['ab'], 'one search batch at a time');
deferred[0].resolve({tracks: [], suggestions: ['stale']}); await wait(5);
assert.deepEqual(calls, ['ab', 'abc']);
assert.equal(states.some(x => x.suggestions.includes('stale')), false, 'old replies never replace the current query');
deferred[1].resolve({tracks: [], suggestions: ['current']}); await wait(5);
assert.deepEqual(states.at(-1).suggestions, ['current']);
engine.setQuery(''); assert.equal(states.at(-1).loading, false); assert.deepEqual(states.at(-1).suggestions, []);
engine.setQuery('abc'); assert.deepEqual(states.at(-1).suggestions, ['current'], 'returning to a query uses the session cache');
engine.setQuery('last'); await wait(15); engine.dispose();
const count = states.length; deferred[2].resolve({tracks: [], suggestions: ['late']}); await wait(5);
assert.equal(states.length, count, 'closing search prevents updates and queued work');
console.log('ok   recent history, deduplication, debounce, stale-response isolation, bounded concurrency, caching and cleanup');
